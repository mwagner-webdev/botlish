/* embed.c -- writes templates.h: each template file NAME.EXT.in as the C
 * array tpl_NAME_EXT (a NUL-terminated text), so that the tool carries its
 * templates and reads no file of its own at run time.
 *
 *   embed OUT.h TEMPLATE.in... */
#include <stdio.h>
#include <string.h>

int main(int argc, char **argv) {
    if (argc < 3) {
        fprintf(stderr, "usage: embed OUT.h TEMPLATE.in...\n");
        return 2;
    }
    FILE *out = fopen(argv[1], "w");
    if (!out) return 1;
    fputs("/* templates.h -- generated by embed.c from the templates; do not edit. */\n", out);
    for (int i = 2; i < argc; i++) {
        const char *base = strrchr(argv[i], '/');
        base = base ? base + 1 : argv[i];
        char name[256];
        size_t n = strlen(base);
        if (n < 4 || strcmp(base + n - 3, ".in") || n - 3 >= sizeof name) return 2;
        memcpy(name, base, n - 3);
        name[n - 3] = 0;
        for (char *c = name; *c; c++)
            if (*c == '.' || *c == '-') *c = '_';
        FILE *in = fopen(argv[i], "rb");
        if (!in) return 1;
        fprintf(out, "static const char tpl_%s[] = {", name);
        int c, k = 0;
        while ((c = fgetc(in)) != EOF) fprintf(out, "%s0x%02x,", k++ % 16 ? "" : "\n    ", c);
        fputs("\n    0x00};\n", out);
        fclose(in);
    }
    return fclose(out) == 0 ? 0 : 1;
}
