#!/usr/bin/env python3
# extract-reference.py -- writes audit/declaration-summaries/tools/reference.tcl:
# the recursive component walks as they were before the declaration summaries
# (PARAMETERIZED-DECLARATION-SUMMARIES-MILESTONE-1.md), taken from a git
# revision, renamed into ::reference::NS so that the audit tools can compare
# them with the compiler's summaries on every type the old walks finish on.
# Audit-only: nothing in the compiler loads it.
#
#   python3 -I audit/declaration-summaries/tools/extract-reference.py [REV]
import re, subprocess, sys, os

REV = sys.argv[1] if len(sys.argv) > 1 else "17b0e669"
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))

# file -> (namespace, [proc names])
PROCS = {
    "hir/callables.tcl": ("callables", ["Bearing", "CarriedErrors", "CarriedInto", "BearingNamed", "HasMutArray"]),
    "hir/types.tcl": ("types", ["Totality", "Components", "SendClass", "SendStruct", "SendComponents",
                                "MentionsMutable", "MentionsMutableFrom", "HashClass"]),
    "hir/mutvec.tcl": ("mutvec", ["MayHoldVector"]),
    "hir/staticdeps.tcl": ("staticdeps", ["CanCarry"]),
    "hir/decimal.tcl": ("decimal", ["Mentions"]),
    "hir/structs.tcl": ("structs", ["MutableComponent"]),
    "hir/sourcetypes.tcl": ("sourcetypes", ["ValueStability"]),
}

def proc_text(source, ns, name):
    m = re.search(r"^proc hir::%s::%s \{" % (ns, re.escape(name)), source, re.M)
    if not m:
        raise SystemExit("no proc hir::%s::%s at %s" % (ns, name, REV))
    i = m.start()
    # The body ends at the first line that is exactly "}" after the header.
    j = source.index("\n}\n", i) + 3
    return source[i:j]

out = ["# reference.tcl -- GENERATED by extract-reference.py from revision %s: the" % REV,
       "# recursive component walks before the declaration summaries, in",
       "# ::reference::NS (audit-only; PARAMETERIZED-DECLARATION-SUMMARIES-",
       "# MILESTONE-1.md). Every named struct's fields are read through",
       "# ::reference::Fields, which counts them and stops a walk past",
       "# ::reference::budget reads (an unfolding that would not end) with the",
       "# error REFERENCE-BUDGET.",
       "",
       "namespace eval ::reference {",
       "    variable budget 5000",
       "    variable reads 0",
       "    # 1 once a walk read a field type the type bound had cut.",
       "    variable cut 0",
       "}",
       "proc ::reference::Fields {type} {",
       "    variable budget",
       "    variable reads",
       "    variable cut",
       "    if {[incr reads] > $budget || [string length $type] > 4000} {",
       "        # (A walk past the budget, or through types this large -- an",
       "        # argument doubled at every step -- does not finish.)",
       "        error REFERENCE-BUDGET",
       "    }",
       "    set fields [hir::structs::AppliedFieldTypes $type]",
       "    if {!$cut && [string length $type] < 2000} {",
       "        # Did the type bound cut what the substitution made?",
       "        set saved [list $::hir::types::aggregateDepth $::hir::types::appliedDepth]",
       "        set ::hir::types::aggregateDepth 1000",
       "        set ::hir::types::appliedDepth 1000",
       "        try {",
       "            set uncut [hir::structs::AppliedFieldTypes $type]",
       "        } finally {",
       "            lassign $saved ::hir::types::aggregateDepth ::hir::types::appliedDepth",
       "        }",
       "        if {$uncut ne $fields} {",
       "            set cut 1",
       "        }",
       "    }",
       "    return $fields",
       "}",
       "proc ::reference::Run {script} {",
       "    variable reads",
       "    variable cut",
       "    set reads 0",
       "    set cut 0",
       "    set ::reference::callables::visiting {}",
       "    set ::reference::callables::carriedVisiting {}",
       "    set ::reference::callables::hasVisiting {}",
       "    if {[catch {uplevel 1 $script} result options]} {",
       "        if {$result eq \"REFERENCE-BUDGET\" || [string match {too many nested evaluations*} $result]} {",
       "            return -code error -errorcode REFERENCE-BUDGET REFERENCE-BUDGET",
       "        }",
       "        return -options $options $result",
       "    }",
       "    return $result",
       "}",
       ""]
for path, (ns, names) in PROCS.items():
    source = subprocess.run(["git", "-C", ROOT, "show", "%s:%s" % (REV, path)],
                            capture_output=True, text=True, check=True).stdout
    out.append("namespace eval ::reference::%s { namespace path ::hir::%s }" % (ns, ns))
    for name in names:
        text = proc_text(source, ns, name)
        text = text.replace("proc hir::%s::%s " % (ns, name), "proc ::reference::%s::%s " % (ns, name), 1)
        text = text.replace("hir::structs::AppliedFieldTypes $type", "::reference::Fields $type")
        text = text.replace("[AppliedFieldTypes $type]", "[::reference::Fields $type]")
        text = text.replace("{AppliedFieldTypes $type}", "{::reference::Fields $type}")
        out.append(text)
open(os.path.join(ROOT, "audit/declaration-summaries/tools/reference.tcl"), "w").write("\n".join(out))
print("wrote reference.tcl from", REV)
