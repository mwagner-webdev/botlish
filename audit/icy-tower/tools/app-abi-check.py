#!/usr/bin/env python3
# app-abi-check.py -- the C ABI of macos_app.bot's own C declarations (the
# alert, ICY-TOWER-MACOS-APP-MILESTONE-1.md, "Terminal-free error
# reporting") against the macOS SDK's headers, as abi-check.py checks the
# SDL3 binding's against SDL3's:
#
#   python3 -I audit/icy-tower/tools/app-abi-check.py WORK [GAME]
#
# macos_app.bot declares getenv, CFStringCreateWithCString, CFRelease and
# CFUserNotificationDisplayAlert by hand (no generated CoreFoundation
# binding exists): a declaration is a claim about the C ABI that only the
# compiler can confirm. This writes a C++ translation unit that includes
# <CoreFoundation/CoreFoundation.h> and <stdlib.h> and compares each
# declaration's parameters and result with the prototype's, by template
# deduction from the function's own type: a C scalar exactly (CFTimeInterval
# a double, CFOptionFlags an unsigned long, CFStringEncoding an unsigned
# int), a std::ffi::c::Ptr[std::ffi::c::Void] any object pointer (CF's
# opaque references), any other pointer its pointee; the symbol each
# `named "..."` gives; and the constants the module writes as numbers
# (kCFStringEncodingUTF8, kCFUserNotificationStopAlertLevel). Built and run
# with the host's clang++ (on the Mac: Apple clang for arm64-apple-macos);
# nothing is called. Exit status 1 on any FAIL.
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.join(HERE, "..", "..", "..", "examples", "games", "icy-tower")
SCALARS = {"Char": "char", "UChar": "unsigned char", "Int": "int", "UInt": "unsigned int", "Long": "long",
           "ULong": "unsigned long", "Double": "double", "Float": "float"}
CONSTANTS = {"utf8": "kCFStringEncodingUTF8", "stop_alert": "kCFUserNotificationStopAlertLevel"}


def declarations(text):
    out = []
    for m in re.finditer(r'^private extern c fn (\w+) named "(\w+)"\((.*)\) -> (\S+)', text, re.M):
        params = []
        for p in m.group(3).split(", "):
            name, t = p.split(": ", 1)
            params.append((name, t.split(" ")[0]))
        out.append((m.group(1), m.group(2), params, m.group(4)))
    return out


def c_check(arg, botlish):
    if botlish.startswith("std::ffi::c::Ptr["):
        inner = botlish[len("std::ffi::c::Ptr["):-1]
        if inner == "std::ffi::c::Void":
            return "std::is_pointer_v<%s>" % arg
        return "std::is_pointer_v<%s> && std::is_same_v<std::remove_cv_t<std::remove_pointer_t<%s>>, %s>" % (
            arg, arg, SCALARS[inner[len("std::ffi::c::"):]])
    if botlish == "unit":
        return "std::is_void_v<%s>" % arg
    return "std::is_same_v<std::remove_cv_t<%s>, %s>" % (arg, SCALARS[botlish[len("std::ffi::c::"):]])


def main(argv):
    if len(argv) not in (1, 2):
        print("usage: app-abi-check.py WORK [GAME]", file=sys.stderr)
        return 2
    work = argv[0]
    game = argv[1] if len(argv) == 2 else GAME
    os.makedirs(work, exist_ok=True)
    with open(os.path.join(game, "macos_app.bot"), encoding="utf-8") as f:
        text = f.read()
    decls = declarations(text)
    lines, checks = [], 0
    for name, symbol, params, result in decls:
        f = "decltype(&::%s)" % symbol
        lines.append('    report(std::tuple_size_v<args_of<%s>> == %d, "%s (%s) takes %d parameters");' % (f, len(params), name, symbol, len(params)))
        checks += 1
        for i, (pname, ptype) in enumerate(params):
            lines.append('    report(%s, "%s parameter %d (%s): %s");' % (
                c_check("std::tuple_element_t<%d, args_of<%s>>" % (i, f), ptype), symbol, i + 1, pname, ptype))
            checks += 1
        lines.append('    report(%s, "%s result: %s");' % (c_check("result_of<%s>" % f, result), symbol, result))
        checks += 1
    for fn, const in CONSTANTS.items():
        m = re.search(r"^private fn %s\(\) -> \S+:\n    (\d+)$" % fn, text, re.M)
        value = m.group(1) if m else "-1"
        lines.append('    report((unsigned long long)(%s) == %sULL, "%s() is %s, %s");' % (const, value, fn, value, const))
        checks += 1
    cpp = os.path.join(work, "app-abi-check.cpp")
    with open(cpp, "w", encoding="utf-8") as out:
        out.write("""// GENERATED by audit/icy-tower/tools/app-abi-check.py.
#include <CoreFoundation/CoreFoundation.h>
#include <stdlib.h>
#include <cstdio>
#include <tuple>
#include <type_traits>

template <typename> struct signature;
template <typename R, typename... A> struct signature<R (*)(A...)> {
    using result = R;
    using args = std::tuple<A...>;
};
template <typename F> using args_of = typename signature<F>::args;
template <typename F> using result_of = typename signature<F>::result;

static int failures;
static void report(bool ok, const char *what) {
    std::printf("%s %s\\n", ok ? "PASS" : "FAIL", what);
    failures += !ok;
}

int main() {
""" + "\n".join(lines) + """
    std::printf("%d checks, %d failed\\n", """ + str(checks) + """, failures);
    return failures ? 1 : 0;
}
""")
    print("app-abi-check: %d declarations of macos_app.bot, %d checks -> %s" % (len(decls), checks, cpp))
    if len(decls) != 4:
        print("FAIL: macos_app.bot declares %d C functions, not the 4 this check knows" % len(decls))
        return 1
    exe = os.path.join(work, "app-abi-check")
    build = subprocess.run([os.environ.get("CXX", "clang++"), "-std=c++17", "-o", exe, cpp, "-framework", "CoreFoundation"],
                           capture_output=True, text=True)
    if build.returncode:
        print(build.stdout + build.stderr)
        print("FAIL: the check does not compile")
        return 1
    run = subprocess.run([exe], capture_output=True, text=True)
    sys.stdout.write(run.stdout)
    return run.returncode


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
