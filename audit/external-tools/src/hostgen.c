/* hostgen.c -- the hostgen package's `host-module` tool
 * (EXTERNAL-COMPILER-TOOLS-AND-TARGET-PACKAGES-MILESTONE-1.md, experiment
 * E): a prototype shaped like the future React Native generator. From one
 * Botlish native library's manifest (schema 2) it writes a host package:
 *
 *   package.json              the package's manifest, naming the library,
 *                             the manifest's digest and the runtime ABI
 *   src/NativeMODULE.ts       the foreign-interface specification: one
 *                             method per export, in a JavaScript host's types
 *   adapter/LIB_host.h, .c    the adapter: a JavaScript-like host's values
 *                             (numbers are doubles, strings, booleans) in,
 *                             the C ABI's calls, host values or host errors out
 *   botlish/LIB.h, libLIB.a   the library, copied
 *   CMakeLists.txt            the build of the adapter and the library
 *
 *   botlish tool -out DIR -artifact LIB.manifest.json host-module
 *                [-name NPM-NAME] [-module MODULE]
 *
 * It reads the manifest and nothing else of Botlish: no HIR, no source.
 * The host's policy is its own, not the ABI's: an int crosses as a
 * JavaScript number only within the safe-integer range (2^53 - 1), both
 * ways (a RangeError otherwise, never a rounded value). */
#include "toolkit.h"

#include <ctype.h>

static char *camel(const char *name) {
    char *out = tk_alloc(strlen(name) + 1);
    size_t o = 0;
    int up = 0;
    for (const char *c = name; *c; c++) {
        if (*c == '_') { up = 1; continue; }
        out[o++] = up ? (char)toupper((unsigned char)*c) : *c;
        up = 0;
    }
    out[o] = 0;
    return out;
}

static char *pascal(const char *name) {
    char *out = camel(name);
    out[0] = (char)toupper((unsigned char)out[0]);
    return out;
}

static const char *ts_type(tk_type t) {
    switch (t) {
    case T_INT: case T_FLOAT64: return "number";
    case T_BOOL: return "boolean";
    case T_STR: return "string";
    default: return "void";
    }
}

static void comment(tk_text *t, const char *s) {
    for (; *s; s++) {
        if (s[0] == '*' && s[1] == '/') tk_printf(t, "* /");
        else tk_printf(t, "%c", *s);
    }
}

static void emit_spec(const tk_library *lib, const char *module, tk_text *t) {
    tk_printf(t, "// Native%s.ts -- the host interface of the Botlish native library %s,\n"
                 "// generated by hostgen host-module from %s.manifest.json. Do not edit.\n"
                 "//\n"
                 "// A method fails by throwing: a BotlishError (code: the error's identity)\n"
                 "// for a declared or runtime error, a TypeError for an argument of the\n"
                 "// wrong type, a RangeError for an int outside the safe-integer range.\n\n",
              module, lib->library, lib->library);
    tk_printf(t, "export interface Spec {\n");
    for (size_t e = 0; e < lib->nexports; e++) {
        const tk_export *x = &lib->exports[e];
        char *method = camel(x->name);
        tk_printf(t, "  /** ");
        comment(t, x->botlish);
        tk_printf(t, " */\n  %s(", method);
        for (size_t p = 0; p < x->nparams; p++) {
            char *param = camel(x->params[p].name);
            tk_printf(t, "%s%s: %s", p ? ", " : "", param, ts_type(x->params[p].type));
            free(param);
        }
        tk_printf(t, "): %s;\n", ts_type(x->result));
        free(method);
    }
    tk_printf(t, "}\n\nexport const methods = [");
    for (size_t e = 0; e < lib->nexports; e++) {
        char *method = camel(lib->exports[e].name);
        tk_printf(t, "%s\"%s\"", e ? ", " : "", method);
        free(method);
    }
    tk_printf(t, "] as const;\n\nexport const module = \"%s\";\n", module);
}

static void emit_header(const tk_library *lib, tk_text *t) {
    const char *L = lib->library;
    tk_printf(t,
        "/* %s_host.h -- a JavaScript-like host's adapter over the Botlish native\n"
        " * library %s, generated by hostgen host-module. Do not edit. */\n"
        "#ifndef %s_HOST_H\n#define %s_HOST_H\n\n"
        "#include <stdbool.h>\n#include <stddef.h>\n\n"
        "typedef enum { HV_UNDEFINED = 0, HV_NUMBER, HV_BOOLEAN, HV_STRING } hv_kind;\n\n"
        "/* A host value: a number (a double, as JavaScript's), a boolean, a\n"
        " * string (UTF-8 bytes) or undefined. */\n"
        "typedef struct {\n    hv_kind kind;\n    double number;\n    bool boolean;\n    const char *text;\n    size_t length;\n} hv_value;\n\n"
        "/* A call's outcome: its value, or its error (the host's error class:\n"
        " * TypeError, RangeError or BotlishError; the code and the message). A\n"
        " * string value's bytes are owned by the result until it is released. */\n"
        "typedef struct {\n    bool failed;\n    char error[16];\n    char code[128];\n    char message[512];\n    hv_value value;\n    char *storage;\n} hv_result;\n\n"
        "typedef struct %s_host %s_host;\n\n"
        "/* Opens the library's instance (one per host thread); 0 or -1 with MESSAGE. */\n"
        "int %s_host_open(%s_host **host, char *message, size_t size);\n"
        "void %s_host_close(%s_host *host);\n"
        "/* Calls METHOD (a Spec method's name) with ARGS. */\n"
        "void %s_host_call(%s_host *host, const char *method, const hv_value *args, size_t count, hv_result *result);\n"
        "void %s_host_result_release(hv_result *result);\n\n"
        "#endif\n", L, L, L, L, L, L, L, L, L, L, L, L, L);
}

static void emit_adapter(const tk_library *lib, tk_text *t) {
    const char *L = lib->library;
    tk_printf(t,
        "/* %s_host.c -- generated by hostgen host-module from %s.manifest.json\n"
        " * (runtime ABI %s). Do not edit. */\n"
        "#include <math.h>\n#include <stdint.h>\n#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n\n"
        "#include \"%s\"\n#include \"%s_host.h\"\n\n"
        "struct %s_host { %s_instance *instance; };\n\n"
        "#define SAFE_INTEGER 9007199254740991.0\n\n",
        L, L, lib->runtimeAbi, lib->header, L, L, L);
    tk_printf(t,
        "static void fail(hv_result *r, const char *error, const char *code, const char *message) {\n"
        "    r->failed = true;\n"
        "    snprintf(r->error, sizeof r->error, \"%%s\", error);\n"
        "    snprintf(r->code, sizeof r->code, \"%%s\", code);\n"
        "    snprintf(r->message, sizeof r->message, \"%%s\", message);\n"
        "}\n\n"
        "/* A Botlish error E as the host's BotlishError (its identity the code),\n"
        " * released with RELEASE (the manifest's). */\n"
        "static void botlish_error(hv_result *r, int32_t status, %s_error *e, int32_t (*release)(%s_error **)) {\n"
        "    char code[128] = \"\", message[512] = \"\";\n"
        "    const uint8_t *p;\n"
        "    size_t n;\n"
        "    if (e && %s_error_identity(e, &p, &n) == %s_STATUS_OK) snprintf(code, sizeof code, \"%%.*s\", (int)n, (const char *)p);\n"
        "    if (e && %s_error_message(e, &p, &n) == %s_STATUS_OK) snprintf(message, sizeof message, \"%%.*s\", (int)n, (const char *)p);\n"
        "    if (!code[0]) snprintf(code, sizeof code, \"STATUS-%%d\", (int)status);\n"
        "    fail(r, \"BotlishError\", code, message);\n"
        "    if (e) release(&e);\n"
        "}\n\n",
        L, L, L, L, L, L);
    tk_printf(t,
        "static int arg_int(hv_result *r, const hv_value *a, const char *name, int64_t *out) {\n"
        "    if (a->kind != HV_NUMBER) { fail(r, \"TypeError\", \"ARGUMENT-TYPE\", name); return 0; }\n"
        "    if (a->number != floor(a->number) || fabs(a->number) > SAFE_INTEGER) { fail(r, \"RangeError\", \"NUMBER-NOT-SAFE-INTEGER\", name); return 0; }\n"
        "    *out = (int64_t)a->number;\n"
        "    return 1;\n"
        "}\n\n"
        "static inline int arg_float64(hv_result *r, const hv_value *a, const char *name, double *out) {\n"
        "    if (a->kind != HV_NUMBER) { fail(r, \"TypeError\", \"ARGUMENT-TYPE\", name); return 0; }\n"
        "    *out = a->number;\n"
        "    return 1;\n"
        "}\n\n"
        "static inline int arg_bool(hv_result *r, const hv_value *a, const char *name, bool *out) {\n"
        "    if (a->kind != HV_BOOLEAN) { fail(r, \"TypeError\", \"ARGUMENT-TYPE\", name); return 0; }\n"
        "    *out = a->boolean;\n"
        "    return 1;\n"
        "}\n\n"
        "static inline int arg_str(hv_result *r, const hv_value *a, const char *name, const uint8_t **p, size_t *n) {\n"
        "    if (a->kind != HV_STRING) { fail(r, \"TypeError\", \"ARGUMENT-TYPE\", name); return 0; }\n"
        "    *p = (const uint8_t *)a->text;\n"
        "    *n = a->length;\n"
        "    return 1;\n"
        "}\n\n"
        "static inline void result_int(hv_result *r, int64_t v) {\n"
        "    if (v > (int64_t)SAFE_INTEGER || v < -(int64_t)SAFE_INTEGER) { fail(r, \"RangeError\", \"RESULT-NOT-SAFE-INTEGER\", \"the result is beyond a number's safe integers\"); return; }\n"
        "    r->value.kind = HV_NUMBER;\n"
        "    r->value.number = (double)v;\n"
        "}\n\n");
    tk_printf(t,
        "int %s_host_open(%s_host **host, char *message, size_t size) {\n"
        "    %s_host *h = calloc(1, sizeof *h);\n"
        "    %s_error *e = NULL;\n"
        "    if (!h) { snprintf(message, size, \"out of memory\"); return -1; }\n"
        "    if (%s(&h->instance, &e) != %s_STATUS_OK) {\n"
        "        const uint8_t *p; size_t n;\n"
        "        if (e && %s_error_message(e, &p, &n) == %s_STATUS_OK) snprintf(message, size, \"%%.*s\", (int)n, (const char *)p);\n"
        "        if (e) %s_error_release(&e);\n"
        "        free(h);\n"
        "        return -1;\n"
        "    }\n"
        "    *host = h;\n"
        "    return 0;\n"
        "}\n\n"
        "void %s_host_close(%s_host *host) {\n"
        "    if (!host) return;\n"
        "    %s(host->instance);\n"
        "    free(host);\n"
        "}\n\n"
        "void %s_host_result_release(hv_result *result) {\n"
        "    free(result->storage);\n"
        "    memset(result, 0, sizeof *result);\n"
        "}\n\n",
        L, L, L, L, lib->create, L, L, L, L, L, L, lib->destroy, L);
    tk_printf(t,
        "void %s_host_call(%s_host *host, const char *method, const hv_value *args, size_t count, hv_result *r) {\n"
        "    memset(r, 0, sizeof *r);\n", L, L);
    for (size_t e = 0; e < lib->nexports; e++) {
        const tk_export *x = &lib->exports[e];
        char *method = camel(x->name);
        tk_printf(t, "    if (!strcmp(method, \"%s\")) {\n        /* ", method);
        comment(t, x->botlish);
        tk_printf(t, " */\n");
        tk_printf(t, "        if (count != %zu) { fail(r, \"TypeError\", \"ARGUMENT-COUNT\", \"%s takes %zu argument%s\"); return; }\n",
                  x->nparams, method, x->nparams, x->nparams == 1 ? "" : "s");
        for (size_t p = 0; p < x->nparams; p++) {
            const char *n = x->params[p].name;
            switch (x->params[p].type) {
            case T_INT: tk_printf(t, "        int64_t a%zu;\n        if (!arg_int(r, &args[%zu], \"%s\", &a%zu)) return;\n", p, p, n, p); break;
            case T_FLOAT64: tk_printf(t, "        double a%zu;\n        if (!arg_float64(r, &args[%zu], \"%s\", &a%zu)) return;\n", p, p, n, p); break;
            case T_BOOL: tk_printf(t, "        bool a%zu;\n        if (!arg_bool(r, &args[%zu], \"%s\", &a%zu)) return;\n", p, p, n, p); break;
            case T_STR: tk_printf(t, "        const uint8_t *a%zu;\n        size_t a%zu_len;\n        if (!arg_str(r, &args[%zu], \"%s\", &a%zu, &a%zu_len)) return;\n", p, p, p, n, p, p); break;
            default: break;
            }
        }
        switch (x->result) {
        case T_INT: tk_printf(t, "        int64_t v;\n"); break;
        case T_BOOL: tk_printf(t, "        bool v;\n"); break;
        case T_FLOAT64: tk_printf(t, "        double v;\n"); break;
        case T_STR: tk_printf(t, "        %s v = {0};\n", lib->bytesType); break;
        default: break;
        }
        tk_printf(t, "        %s_error *e = NULL;\n        int32_t s = %s(host->instance", L, x->symbol);
        for (size_t p = 0; p < x->nparams; p++) {
            if (x->params[p].type == T_STR) tk_printf(t, ", a%zu, a%zu_len", p, p);
            else tk_printf(t, ", a%zu", p);
        }
        if (x->result != T_UNIT) tk_printf(t, ", &v");
        tk_printf(t, ", &e);\n        if (s != %s_STATUS_OK) { botlish_error(r, s, e, %s); return; }\n", L, x->errorRelease);
        switch (x->result) {
        case T_INT: tk_printf(t, "        result_int(r, v);\n"); break;
        case T_BOOL: tk_printf(t, "        r->value.kind = HV_BOOLEAN;\n        r->value.boolean = v;\n"); break;
        case T_FLOAT64: tk_printf(t, "        r->value.kind = HV_NUMBER;\n        r->value.number = v;\n"); break;
        case T_STR:
            tk_printf(t,
                "        /* The host's copy; the Botlish buffer is the caller's to release\n"
                "         * (the manifest's release function). */\n"
                "        r->storage = malloc(v.len + 1);\n"
                "        if (!r->storage) { %s(&v); fail(r, \"RangeError\", \"OUT-OF-MEMORY\", \"no memory for the result\"); return; }\n"
                "        memcpy(r->storage, v.ptr, v.len);\n"
                "        r->storage[v.len] = 0;\n"
                "        r->value.kind = HV_STRING;\n"
                "        r->value.text = r->storage;\n"
                "        r->value.length = v.len;\n"
                "        %s(&v);\n", x->resultRelease, x->resultRelease);
            break;
        default: tk_printf(t, "        r->value.kind = HV_UNDEFINED;\n"); break;
        }
        tk_printf(t, "        return;\n    }\n");
        free(method);
    }
    tk_printf(t, "    fail(r, \"TypeError\", \"NO-SUCH-METHOD\", method);\n}\n");
}

static void emit_package(const tk_library *lib, const char *name, const char *module, const char *digest, tk_text *t) {
    tk_printf(t, "{\n  \"name\": ");
    tk_json_text(t, name);
    tk_printf(t, ",\n  \"version\": \"0.1.0\",\n  \"description\": \"A host module over the Botlish native library %s (generated by hostgen host-module)\",\n", lib->library);
    tk_printf(t, "  \"main\": \"src/Native%s.ts\",\n  \"files\": [\"src\", \"adapter\", \"botlish\", \"CMakeLists.txt\"],\n", module);
    tk_printf(t, "  \"botlish\": {\n    \"library\": \"%s\",\n    \"manifestSha256\": \"%s\",\n    \"runtimeAbi\": \"%s\",\n    \"abi\": 1\n  },\n", lib->library, digest, lib->runtimeAbi);
    tk_printf(t, "  \"hostModule\": {\n    \"name\": \"%s\",\n    \"spec\": \"src/Native%s.ts\",\n    \"adapter\": \"adapter/%s_host.c\"\n  }\n}\n", module, module, lib->library);
}

static void emit_cmake(const tk_library *lib, tk_text *t) {
    const char *L = lib->library;
    tk_printf(t, "# generated by hostgen host-module. Do not edit.\n"
                 "cmake_minimum_required(VERSION 3.16)\nproject(%s_host C)\n\n"
                 "add_library(%s_host STATIC adapter/%s_host.c)\n"
                 "target_include_directories(%s_host PUBLIC adapter botlish)\n"
                 "target_link_libraries(%s_host PUBLIC ${CMAKE_CURRENT_SOURCE_DIR}/botlish/%s", L, L, L, L, L, lib->staticLib);
    for (size_t i = 0; i < lib->ndependencies; i++) tk_printf(t, " %s", lib->dependencies[i]);
    for (size_t i = 0; i < lib->nlink; i++) tk_printf(t, " %s", lib->link[i]);
    tk_printf(t, " m)\n");
}

static void copy_file(const char *from, const char *dir, const char *name) {
    size_t len;
    char *bytes = tk_read(from, &len);
    if (!bytes) tk_die(1, "TOOL-INPUT", from, "cannot read: %s", strerror(errno));
    tk_text t = {bytes, len, len + 1};
    tk_write(dir, name, &t);
    free(bytes);
}

int main(int argc, char **argv) {
    tk_request r = tk_open_request("host-module");
    const char *name = NULL, *module = NULL;
    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "-name") && i + 1 < argc) name = argv[++i];
        else if (!strcmp(argv[i], "-module") && i + 1 < argc) module = argv[++i];
        else tk_die(64, "TOOL-USAGE", NULL, "unknown argument \"%s\" (host-module [-name NPM-NAME] [-module MODULE])", argv[i]);
    }
    tk_library lib = tk_request_library(&r);
    const char *digest = "";
    for (size_t i = 0; i < r.artifacts->count; i++) {
        const char *kind = json_str(r.artifacts->items[i], "kind");
        if (kind && !strcmp(kind, "native-library")) digest = json_str(r.artifacts->items[i], "sha256");
    }
    char defaultName[300];
    if (!name) {
        snprintf(defaultName, sizeof defaultName, "botlish-%s", lib.library);
        for (char *c = defaultName; *c; c++) if (*c == '_') *c = '-';
        name = defaultName;
    }
    if (!module) module = pascal(lib.library);
    for (const char *c = module; *c; c++)
        if (!isalnum((unsigned char)*c)) tk_die(64, "TOOL-USAGE", NULL, "the module name \"%s\" is no identifier", module);
    tk_text spec = {0}, header = {0}, adapter = {0}, package = {0}, cmake = {0};
    emit_spec(&lib, module, &spec);
    emit_header(&lib, &header);
    emit_adapter(&lib, &adapter);
    emit_package(&lib, name, module, digest ? digest : "", &package);
    emit_cmake(&lib, &cmake);
    char path[400];
    snprintf(path, sizeof path, "src/Native%s.ts", module);
    tk_write(r.output, path, &spec);
    snprintf(path, sizeof path, "adapter/%s_host.h", lib.library);
    tk_write(r.output, path, &header);
    snprintf(path, sizeof path, "adapter/%s_host.c", lib.library);
    tk_write(r.output, path, &adapter);
    tk_write(r.output, "package.json", &package);
    tk_write(r.output, "CMakeLists.txt", &cmake);
    char *from = tk_join(lib.dir, lib.header);
    snprintf(path, sizeof path, "botlish/%s", lib.header);
    copy_file(from, r.output, path);
    from = tk_join(lib.dir, lib.staticLib);
    snprintf(path, sizeof path, "botlish/%s", lib.staticLib);
    copy_file(from, r.output, path);
    printf("host-module: %s (%s, module %s), %zu method%s\n", r.output, name, module, lib.nexports, lib.nexports == 1 ? "" : "s");
    tk_finish();
    return 0;
}
