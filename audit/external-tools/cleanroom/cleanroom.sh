#!/usr/bin/env bash
# cleanroom.sh -- the clean-room acceptance of
# EXTERNAL-COMPILER-TOOLS-AND-TARGET-PACKAGES-MILESTONE-1.md: the single-file
# compiler and explicitly provided packages, nothing else.
#
#   audit/external-tools/cleanroom/cleanroom.sh BOTLISH REPO RESULTS
#
# BOTLISH is the single-file compiler (single/build.sh's output), REPO a
# directory of the experiment's .botpkg artifacts (audit/external-tools/
# tools/packages.sh OUT NATIVE-DIR BOTLISH writes them to OUT/repo, from the
# build of the native backend BOTLISH was built from: the target support
# package's runtime ABI is that build's). The room is a fresh directory holding a copy of BOTLISH, the
# artifacts and the experiments' own inputs (the 2048 wrapper engine.bot, the
# probe tool's C source, the host harness, the game's steps); the experiments
# run there with an empty environment (env -i: HOME and the caches inside the
# room, PATH=/usr/bin:/bin for the system's cc, ld, ar, objcopy), from the
# room, never this checkout. Under strace (when installed) every file the run
# opens and every program it starts is recorded, and the run is refused if
# any of them is in this checkout or is a Tcl installation of the system:
# the compiler is the single file, and the tools are the packages' own.
#
#   A  an ordinary pure-Botlish package (game2048) installed and imported
#   B  an external tool package: installing, verifying and compiling run
#      nothing; `botlish tool` runs exactly the named tool, its arguments
#      exact (the probe tool, packed in the room by the single executable)
#   C  a target support package: an executable linked with its runtime
#      archive; removed, a precise refusal
#   D  a native library of real Botlish code (the 2048 engine) built by the
#      single executable, a C caller generated by emit-caller from its
#      manifest, compiled and run
#   E  a React-Native-shaped host module (host-module) over the same library,
#      its adapter compiled into a host harness and run
#   2048  both callers' games compared with the single executable's
#      interpreter playing the same steps
#
# RESULTS gets each step's output, the traces and a summary; the exit status
# is 0 only when every check passed.
set -euo pipefail

if [[ $# -ne 3 ]]; then
    echo "usage: cleanroom.sh BOTLISH REPO RESULTS" >&2
    exit 2
fi
botlish=$(realpath "$1")
repo=$(realpath "$2")
results=$(realpath -m "$3")
here=$(cd "$(dirname "$0")" && pwd)
experiment=$(dirname "$here")
checkout=$(cd "$experiment/../.." && pwd)
room=$(mktemp -d /tmp/botlish-cleanroom.XXXXXX)
mkdir -p "$results" "$room/bin" "$room/home" "$room/repo" "$room/app" "$room/inputs"
cp "$botlish" "$room/bin/botlish"
cp "$repo"/*.botpkg "$room/repo/"
cp "$experiment/2048/engine.bot" "$experiment/src/probe-tool.c" "$room/inputs/"
cp "$here/harness.c" "$room/inputs/harness.c"

# The game's steps: the tests' linear congruential sequence
# (tests/external-tools.test's et2048Steps), 160 of them.
x=12345
steps=()
for ((i = 0; i < 160; i++)); do
    x=$(( (x * 1103515245 + 12345) % 2147483648 ))
    d=$(( (x >> 16) % 4 ))
    if (( ((x >> 8) % 10) == 0 )); then t=4; else t=2; fi
    steps+=("$d $t")
done
printf '%s\n' "${steps[@]}" >"$room/inputs/steps.txt"
{
    printf 'new_game\nspawn_first\t@\t2\nspawn_first\t@\t4\n'
    for s in "${steps[@]}"; do
        printf 'move\t@\t%s\nspawn_first\t@\t%s\n' "${s% *}" "${s#* }"
    done
} >"$room/inputs/calls.txt"
literal=$(printf '[%s], ' "${steps[@]/ /, }")
literal="[${literal%, }]"
cat >"$room/inputs/oracle.bot" <<EOF
import std::list
import engine

fn play(state: str, steps: List[List[int]], i: int, states: List[str]) -> List[str] errors engine::InvalidState, engine::InvalidDirection, engine::InvalidSpawn:
    if i >= std::list::length(steps):
        return states
    step = std::list::get(steps, i, [0, 2])
    moved = engine::move(state, std::list::get(step, 0, 0))
    next = engine::spawn_first(moved, std::list::get(step, 1, 2))
    play(next, steps, i + 1, std::list::append(std::list::append(states, moved), next))

fn game(steps: List[List[int]]) -> List[str] errors engine::InvalidState, engine::InvalidDirection, engine::InvalidSpawn:
    start = engine::spawn_first(engine::spawn_first(engine::new_game(), 2), 4)
    play(start, steps, 0, [start])

states = game($literal):
    on engine::InvalidState:
        []
    on engine::InvalidDirection:
        []
    on engine::InvalidSpawn:
        []
states
EOF

# The run inside the room: only the room's files, the system's programs.
cat >"$room/run.sh" <<'EOF'
set -euo pipefail
room=$1
cd "$room/app"
b="$room/bin/botlish"
pass() { echo "PASS $*"; }
fail() { echo "FAIL $*"; exit 1; }

echo '{"schema": 1, "dependencies": {}}' >botlish.json

# A: an ordinary pure-Botlish package.
"$b" add "$room/repo/game2048-0.1.0.botpkg" >"$room/out-A-add.txt"
printf 'import game2048\n\ngame2048::new_game().score\n' >ordinary.bot
"$b" -warnings off ordinary.bot >"$room/out-A-run.txt"
grep -q 'value: 0' "$room/out-A-run.txt" && pass "A ordinary package imported and run" || fail A

# B: an external tool package, packed in the room by the single executable.
mkdir -p "$room/probe/tools/linux-x86_64"
cc -O2 -DPROBE_MARKER="\"$room/marker.txt\"" -o "$room/probe/tools/linux-x86_64/probe" "$room/inputs/probe-tool.c"
cat >"$room/probe/botlish.json" <<'JSON'
{"schema": 4, "name": "probe_tools", "version": "0.1.0", "dependencies": {},
 "tools": {"probe": {"protocol": 1, "summary": "records how it was run", "programs": {"linux-x86_64": "tools/linux-x86_64/probe"}}}}
JSON
printf 'fn answer() -> int:\n    42\n' >"$room/probe/probe_tools.bot"
"$b" package pack "$room/probe" -out "$room/repo" >"$room/out-B-pack.txt"
for p in probe_tools abi_tools hostgen; do
    "$b" add "$room/repo/$p-0.1.0.botpkg" >>"$room/out-B-add.txt"
done
"$b" verify >>"$room/out-B-add.txt"
"$b" install >>"$room/out-B-add.txt"
printf 'import probe_tools\n\nprobe_tools::answer()\n' >uses-probe.bot
"$b" -warnings off uses-probe.bot >>"$room/out-B-add.txt"
"$b" tools >"$room/out-B-tools.txt"
[[ ! -e "$room/marker.txt" ]] && pass "B installing, verifying, compiling and listing ran no tool" || fail "B a tool ran without being named"
[[ $(stat -c %a .bot_modules/probe_tools/tools/linux-x86_64/probe) == 644 ]] && pass "B the installed program is not executable" || fail "B executable installed"
"$b" tool -out "$room/out-B" probe ok "a b" "ünï" '$(touch pwned)' '|x' '>y' '' >"$room/out-B-tool.txt" 2>&1
[[ $(cat "$room/marker.txt") == "ran ok" ]] && pass "B tool ran exactly the named tool once" || fail "B marker"
expected=$(printf '%s\n' ok "a b" "ünï" '$(touch pwned)' '|x' '>y' '' | while IFS= read -r w; do printf '%s' "$w" | od -An -tx1 | tr -d ' \n'; echo; done)
[[ $(cat "$room/out-B/argv.hex") == "$expected" && ! -e pwned ]] && pass "B arguments arrived exactly" || fail "B argv"
set +e
"$b" tool -out "$room/out-B2" probe exit 7 2>"$room/out-B-exit.txt"
status=$?
set -e
[[ $status == 7 ]] && pass "B a tool's exit status is the command's" || fail "B exit status $status"

# C: a target support package.
"$b" add "$room/repo/botlish_target_linux-0.1.0.botpkg" -target linux-x86_64 >"$room/out-C-add.txt"
printf 'fn twice(n: int) -> int:\n    n * 2\n\ntwice(21)\n' >hello.bot
"$b" -emit-native-executable -target-support botlish_target_linux hello.bot >"$room/out-C-link.txt" 2>&1
BOTLISH_NATIVE_RESULT="$room/out-C-result.txt" ./hello
grep -q 'target support: botlish_target_linux' "$room/out-C-link.txt" && grep -q 'value {int 42}' "$room/out-C-result.txt" \
    && pass "C an executable linked with the target support package's runtime" || fail C
"$b" remove botlish_target_linux -target linux-x86_64 >>"$room/out-C-add.txt"
rm -f hello
set +e
"$b" -emit-native-executable -target-support botlish_target_linux hello.bot >"$room/out-C-missing.txt" 2>&1
status=$?
set -e
[[ $status == 1 && ! -e hello ]] && grep -q 'NATIVE TARGET-SUPPORT MISSING' "$room/out-C-missing.txt" \
    && pass "C a removed target support package is refused, precisely" || fail "C missing"

# D: a native library of the 2048 engine, and a generated C caller.
cp "$room/inputs/engine.bot" engine.bot
"$b" -warnings error -emit-native-library game -out lib engine.bot >"$room/out-D-library.txt"
"$b" tool -out "$room/gen" -artifact lib/game.manifest.json emit-caller >"$room/out-D-tool.txt"
link=$(sed -n 's/.*"link": \[\(.*\)\]/\1/p' "$room/gen/game_caller.build.json" | tr -d '",')
cc -std=c99 -Wall -Wextra -Werror -I lib "$room/gen/game_caller.c" lib/libgame.a $link -o "$room/caller"
"$room/caller" <"$room/inputs/calls.txt" >"$room/out-D-calls.txt"
pass "D a generated C caller of the real library compiled and ran"

# E: a React-Native-shaped host module over the same library.
"$b" tool -out "$room/hm" -artifact lib/game.manifest.json host-module -name game-2048 >"$room/out-E-tool.txt"
cc -std=c99 -Wall -Wextra -Werror -I "$room/hm/adapter" -I "$room/hm/botlish" "$room/inputs/harness.c" \
    "$room/hm/adapter/game_host.c" "$room/hm/botlish/libgame.a" $link -o "$room/host"
"$room/host" <"$room/inputs/steps.txt" >"$room/out-E-host.txt"
pass "E a host module's adapter compiled into a host and ran"

# 2048: both against the interpreter.
cp "$room/inputs/oracle.bot" oracle.bot
"$b" -warnings off -backend interp oracle.bot >"$room/out-2048-oracle.txt"
grep -o '"[0-9 ]*"' "$room/out-2048-oracle.txt" | tr -d '"' >"$room/oracle-states.txt"
tail -n +3 "$room/out-D-calls.txt" | cut -f4 >"$room/caller-states.txt"
sed -n '3,$p' "$room/out-E-host.txt" | grep '^state ' | cut -c7- >"$room/host-states.txt"
[[ $(wc -l <"$room/oracle-states.txt") -eq 321 ]] || fail "2048 oracle states"
cmp -s "$room/oracle-states.txt" "$room/caller-states.txt" && pass "2048 the C caller played as the interpreter" || fail "2048 caller"
cmp -s "$room/oracle-states.txt" "$room/host-states.txt" && pass "2048 the host module played as the interpreter" || fail "2048 host"
EOF

env_cmd=(env -i "HOME=$room/home" "PATH=/usr/bin:/bin" "LANG=C.UTF-8" "TMPDIR=$room/tmp")
mkdir -p "$room/tmp"
traced=0
if command -v strace >/dev/null 2>&1; then
    traced=1
    set +e
    (cd "$room" && "${env_cmd[@]}" strace -f -qq -e trace=execve,open,openat,stat,newfstatat,access -o "$results/trace.txt" \
        /bin/bash "$room/run.sh" "$room") | tee "$results/summary.txt"
    status=${PIPESTATUS[0]}
    set -e
else
    set +e
    (cd "$room" && "${env_cmd[@]}" /bin/bash "$room/run.sh" "$room") | tee "$results/summary.txt"
    status=${PIPESTATUS[0]}
    set -e
fi
cp "$room"/out-* "$results/" 2>/dev/null || true

if [[ $traced == 1 ]]; then
    # Nothing of this checkout, and no Tcl but the single file's own.
    if grep -F "$checkout" "$results/trace.txt" | grep -v ENOENT >"$results/checkout-access.txt"; then
        echo "FAIL the run reached this checkout ($(wc -l <"$results/checkout-access.txt") accesses: checkout-access.txt)" | tee -a "$results/summary.txt"
        status=1
    else
        echo "PASS the run reached nothing of the checkout ($checkout)" | tee -a "$results/summary.txt"
    fi
    if grep -E '(/usr/(local/)?(lib|share)/(x86_64-linux-gnu/)?tcl[0-9]|/usr/share/tcltk|execve\("[^"]*tclsh)' "$results/trace.txt" \
            | grep -v ENOENT >"$results/system-tcl-access.txt"; then
        echo "FAIL the run used a system Tcl (system-tcl-access.txt)" | tee -a "$results/summary.txt"
        status=1
    else
        echo "PASS the run used no Tcl but the single file's own" | tee -a "$results/summary.txt"
    fi
fi
rm -rf "$room"
exit "$status"
